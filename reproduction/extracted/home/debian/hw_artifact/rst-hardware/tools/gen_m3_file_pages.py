#!/usr/bin/env python3
"""Generate a SystemVerilog include for m3_file_roundtrip_tb.sv."""

from __future__ import annotations

import argparse
from pathlib import Path


CHUNK_WIDTH = 256


def chunk_bytes(data: bytes) -> list[bytes]:
    if not data:
        return [b""]
    return [data[idx : idx + CHUNK_WIDTH] for idx in range(0, len(data), CHUNK_WIDTH)]


def pad_byte(page_idx: int, lane_idx: int) -> int:
    return (page_idx * 73 + lane_idx * 29) & 0xFF


def emit_include(
    input_path: Path,
    output_path: Path,
    max_bytes: int | None = None,
    max_pages: int | None = None,
) -> None:
    data = input_path.read_bytes()
    if max_bytes is not None:
        data = data[:max_bytes]
    chunks = chunk_bytes(data)
    if max_pages is not None:
        chunks = chunks[:max_pages]
        data = b"".join(chunks)
    padded_bytes = len(chunks) * CHUNK_WIDTH

    lines: list[str] = []
    lines.append("// Generated by gen_m3_file_pages.py")
    lines.append(f"// Input file: {input_path}")
    lines.append(f"localparam int FILE_NUM_PAGES = {len(chunks)};")
    lines.append(f"localparam int FILE_INPUT_BYTES = {len(data)};")
    lines.append(f"localparam int FILE_PADDED_BYTES = {padded_bytes};")
    lines.append("")
    lines.append("task automatic load_generated_page(")
    lines.append("    input int page_idx,")
    lines.append("    output symbol_t page [CHUNK_WIDTH],")
    lines.append("    output int valid_bytes")
    lines.append(");")
    lines.append("    begin")
    lines.append("        valid_bytes = 0;")
    lines.append("        for (int i = 0; i < CHUNK_WIDTH; i++) begin")
    lines.append("            page[i] = '0;")
    lines.append("        end")
    lines.append("        case (page_idx)")

    for page_idx, chunk in enumerate(chunks):
        lines.append(f"            {page_idx}: begin")
        lines.append(f"                valid_bytes = {len(chunk)};")
        for lane_idx in range(CHUNK_WIDTH):
            if lane_idx < len(chunk):
                byte_val = chunk[lane_idx]
            else:
                byte_val = pad_byte(page_idx, lane_idx)
            lines.append(f"                page[{lane_idx}] = 9'h{byte_val:03x};")
        lines.append("            end")

    lines.append("            default: begin")
    lines.append('                $fatal(1, "invalid generated page index %0d", page_idx);')
    lines.append("            end")
    lines.append("        endcase")
    lines.append("    end")
    lines.append("endtask")
    lines.append("")

    output_path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate an include for the M3 page-at-a-time file round-trip TB."
    )
    parser.add_argument(
        "--max-bytes",
        type=int,
        help="Optional cap on bytes read from the input file before chunking",
    )
    parser.add_argument(
        "--max-pages",
        type=int,
        help="Optional cap on generated 256-byte pages after chunking",
    )
    parser.add_argument("input_file", type=Path, help="Binary or text file to chunk")
    parser.add_argument("output_include", type=Path, help="Output .svh path")
    args = parser.parse_args()

    emit_include(
        args.input_file,
        args.output_include,
        max_bytes=args.max_bytes,
        max_pages=args.max_pages,
    )


if __name__ == "__main__":
    main()
