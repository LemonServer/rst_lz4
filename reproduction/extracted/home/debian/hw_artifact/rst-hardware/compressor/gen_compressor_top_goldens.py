#!/usr/bin/env python3

from collections import Counter
from pathlib import Path


CHUNK_WIDTH = 256
MAX_DICT_ENTRIES = 63
MIN_SEQ_LEN = 2
MAX_SEQ_LEN = 5
MEMORY_BLOCKS = 2
DICT_BITS = MEMORY_BLOCKS * 64 * 8 - 6


def utility_num(seq_len: int, count: int) -> int:
    return count * (9 * (seq_len - 1)) - (9 * seq_len + 2)


def dict_entry_cost_bits(seq_len: int) -> int:
    return 9 * seq_len + 2


def build_unique_page() -> list[int]:
    return list(range(CHUNK_WIDTH))


def build_sparse_seq5_page() -> list[int]:
    seq_a = [0x1A, 0x2B, 0x3C, 0x4D, 0x5E]
    page = list(range(CHUNK_WIDTH))
    for rep in range(4):
        base = 24 + rep * 56
        page[base : base + len(seq_a)] = seq_a
    return page


def build_sparse_seq4_page() -> list[int]:
    seq_b = [0x61, 0x72, 0x83, 0x94]
    page = list(range(CHUNK_WIDTH))
    for rep in range(4):
        base = 40 + rep * 48
        page[base : base + len(seq_b)] = seq_b
    return page


def compress_reference(page: list[int]) -> tuple[list[int], list[tuple[int, tuple[int, ...]]]]:
    working = list(page)
    dict_entries: list[tuple[int, tuple[int, ...]]] = []
    dict_space = DICT_BITS

    while len(dict_entries) < MAX_DICT_ENTRIES:
        best_seq: tuple[int, ...] | None = None
        best_len = 0
        best_num = 0
        best_den = 1

        for seq_len in range(MIN_SEQ_LEN, MAX_SEQ_LEN + 1):
            counts = Counter(tuple(working[pos : pos + seq_len]) for pos in range(len(working) - seq_len + 1))
            for pos in range(len(working) - seq_len + 1):
                seq = tuple(working[pos : pos + seq_len])
                count = counts[seq]
                cand_num = utility_num(seq_len, count)
                cand_den = dict_entry_cost_bits(seq_len)
                if cand_num <= 0 or dict_space < cand_den:
                    continue
                if best_seq is None or cand_num * best_den > best_num * cand_den:
                    best_seq = seq
                    best_len = seq_len
                    best_num = cand_num
                    best_den = cand_den

        if best_seq is None:
            break

        repl = 0x100 + len(dict_entries)
        new_page: list[int] = []
        pos = 0
        made_replacement = False
        while pos < len(working):
            if tuple(working[pos : pos + best_len]) == best_seq:
                new_page.append(repl)
                pos += best_len
                made_replacement = True
            else:
                new_page.append(working[pos])
                pos += 1

        if not made_replacement:
            break

        dict_entries.append((best_len, best_seq))
        dict_space -= dict_entry_cost_bits(best_len)
        working = new_page

    return working, dict_entries


def emit_symbol(value: int) -> str:
    return f"9'h{value:03x}"


def emit_seq(seq: tuple[int, ...]) -> str:
    parts = ["9'h000"] * 5
    for idx, value in enumerate(seq):
        parts[idx] = emit_symbol(value)
    return "{" + ", ".join(reversed(parts)) + "}"


def emit_task_lines(name: str, page: list[int], compressed: list[int], dict_entries: list[tuple[int, tuple[int, ...]]]) -> list[str]:
    lines: list[str] = []
    lines.append(f"task automatic load_golden_{name};")
    lines.append("    begin")
    lines.append("        expected_dict_count = 0;")
    for idx, value in enumerate(page):
        lines.append(f"        stimulus_page[{idx}] = {emit_symbol(value)};")
    for idx in range(MAX_DICT_ENTRIES):
        if idx < len(dict_entries):
            seq_len, seq = dict_entries[idx]
            lines.append(f"        expected_dict_lens[{idx}] = 3'd{seq_len};")
            lines.append(f"        expected_dict_seqs[{idx}] = {emit_seq(seq)};")
        else:
            lines.append(f"        expected_dict_lens[{idx}] = 3'd0;")
            lines.append(f"        expected_dict_seqs[{idx}] = '0;")
    lines.append(f"        expected_dict_count = {len(dict_entries)};")
    for idx in range(CHUNK_WIDTH):
        if idx < len(compressed):
            lines.append(f"        expected_page_valid[{idx}] = 1'b1;")
            lines.append(f"        expected_page_sym[{idx}] = {emit_symbol(compressed[idx])};")
        else:
            lines.append(f"        expected_page_valid[{idx}] = 1'b0;")
            lines.append(f"        expected_page_sym[{idx}] = 9'h000;")
    lines.append("    end")
    lines.append("endtask")
    lines.append("")
    return lines


def main() -> None:
    cases = {
        "unique_page_no_compress": build_unique_page(),
        "sparse_page_single_iter": build_sparse_seq5_page(),
        "sparse_len4_single_iter": build_sparse_seq4_page(),
    }

    lines = [
        "// Generated by compressor/gen_compressor_top_goldens.py",
        "",
    ]
    for name, page in cases.items():
        compressed, dict_entries = compress_reference(page)
        lines.extend(emit_task_lines(name, page, compressed, dict_entries))

    out_path = Path(__file__).with_name("compressor_top_golden_vectors.svh")
    out_path.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
