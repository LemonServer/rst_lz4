def emit_branch(width: int, layers: list[list[tuple[int, int]]]) -> list[str]:
    lines = [f"            {width}: begin"]
    for stage_idx in range(len(layers) + 1):
        lines.append(f"                keyed_update_t stage{stage_idx} [{width}];")
    lines.append("                keyed_pair_t pair;")
    lines.append("")
    lines.append(f"                for (int i = 0; i < {width}; i++) begin")
    lines.append("                    stage0[i].update = i_updates[i];")
    lines.append("                    stage0[i].key = sort_key(i_updates[i]);")
    lines.append("                end")
    lines.append("")
    for stage_idx, layer in enumerate(layers, start=1):
        prev_stage = f"stage{stage_idx - 1}"
        next_stage = f"stage{stage_idx}"
        lines.append(f"                {next_stage} = {prev_stage};")
        for lhs_idx, rhs_idx in layer:
            lines.append(
                f"                pair = ce_pair({next_stage}[{lhs_idx}], {next_stage}[{rhs_idx}]); "
                f"{next_stage}[{lhs_idx}] = pair.lo; {next_stage}[{rhs_idx}] = pair.hi;"
            )
        lines.append("")
    final_stage = f"stage{len(layers)}"
    lines.append(f"                for (int i = 0; i < {width}; i++) begin")
    lines.append(f"                    o_updates[i] = {final_stage}[i].update;")
    lines.append("                end")
    lines.append("            end")
    return lines


def generate_sorter() -> str:
    lines = [
        "`timescale 1ps / 1ps",
        "`default_nettype none",
        "",
        "// Generated by compressor/sorting_net_verilog_gen.py",
        "module SeqSorter",
        "    import rst_pkg::*;",
        "#(",
        "    parameter int PIPE_WIDTH = PIPE_WIDTH_SEQ2",
        ") (",
        "    input  hashed_update_t i_updates [PIPE_WIDTH],",
        "    output hashed_update_t o_updates [PIPE_WIDTH]",
        ");",
        "    localparam int SORT_KEY_W = 1 + $clog2(BANKS_SEQ5) + $bits(seq_t) + 1 + $clog2(SETS_PER_BANK);",
        "",
        "    typedef logic [SORT_KEY_W-1:0] sort_key_t;",
        "",
        "    typedef struct packed {",
        "        sort_key_t key;",
        "        hashed_update_t update;",
        "    } keyed_update_t;",
        "",
        "    typedef struct packed {",
        "        keyed_update_t lo;",
        "        keyed_update_t hi;",
        "    } keyed_pair_t;",
        "",
        "    function automatic seq_t active_seq(input hashed_update_t update);",
        "        case (PIPE_WIDTH)",
        "            PIPE_WIDTH_SEQ2: active_seq = {27'b0, update.seq[1], update.seq[0]};",
        "            PIPE_WIDTH_SEQ3: active_seq = {18'b0, update.seq[2], update.seq[1], update.seq[0]};",
        "            PIPE_WIDTH_SEQ4: active_seq = {9'b0, update.seq[3], update.seq[2], update.seq[1], update.seq[0]};",
        "            default:         active_seq = update.seq;",
        "        endcase",
        "    endfunction",
        "",
        "    function automatic sort_key_t sort_key(input hashed_update_t update);",
        "        sort_key = {",
        "            ~update.valid,",
        "            update.valid ? update.bank_idx : '0,",
        "            update.valid ? active_seq(update) : '0,",
        "            update.valid ? update.inc : 1'b0,",
        "            update.valid ? update.set_idx : '0",
        "        };",
        "    endfunction",
        "",
        "    function automatic keyed_pair_t ce_pair(",
        "        input keyed_update_t lhs,",
        "        input keyed_update_t rhs",
        "    );",
        "        keyed_pair_t pair;",
        "        begin",
        "            if (rhs.key < lhs.key) begin",
        "                pair.lo = rhs;",
        "                pair.hi = lhs;",
        "            end else begin",
        "                pair.lo = lhs;",
        "                pair.hi = rhs;",
        "            end",
        "            return pair;",
        "        end",
        "    endfunction",
        "",
        "    always_comb begin",
        "        case (PIPE_WIDTH)",
    ]
    for width in sorted(NETWORKS):
        lines.extend(emit_branch(width, NETWORKS[width]))
    lines.extend(
        [
            "            default: begin",
            "                for (int i = 0; i < PIPE_WIDTH; i++) begin",
            "                    o_updates[i] = i_updates[i];",
            "                end",
            "            end",
            "        endcase",
            "    end",
            "endmodule",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    output_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("seq_sorter.sv")
    output_path.write_text(generate_sorter(), encoding="ascii")
    print(f"Generated sorter -> {output_path}")


if __name__ == "__main__":
    main()
